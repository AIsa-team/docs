#!/usr/bin/env python3
"""Keep the model pages in step with the AIsa model price list.

`catalog/models.json` is a snapshot of every callable model on the public price
list (https://api.aisa.one/pricing/models), by vendor and model ID.
`catalog/model-families.json` gives each vendor its family page, display names
and optional per-model notes.

From the two, this script writes the generated blocks of:
- each family page (`models/<slug>.mdx` and its Chinese page): the model table;
- the Model Catalog (`guides/models.mdx` and its Chinese page): every family,
  with its provider, model count and model types.

Prose around the blocks is hand-written. `--refresh` first updates the snapshot
from the live price list and keeps the old one when the list cannot be read.
"""
from __future__ import annotations

import argparse
import json
import re
import sys
import urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SNAPSHOT_PATH = Path("catalog/models.json")
FAMILIES_PATH = Path("catalog/model-families.json")
PRICE_LIST = "https://api.aisa.one/pricing/models"
CATALOG_PAGE = "guides/models"
GENERATOR = "generated by scripts/model_pages.py from catalog/models.json; do not edit"
TABLE_START = "{/* model-table:start (" + GENERATOR + ") */}"
TABLE_END = "{/* model-table:end */}"
FAMILIES_START = "{/* model-families:start (" + GENERATOR + ") */}"
FAMILIES_END = "{/* model-families:end */}"

KINDS = ("text", "image", "video", "embedding", "rerank")
KIND_LABELS = {
    "en": {"text": "Text", "image": "Image", "video": "Video", "embedding": "Embedding", "rerank": "Rerank"},
    "zh": {"text": "文本", "image": "图像", "video": "视频", "embedding": "Embedding", "rerank": "重排序"},
}
ROUTE_ORDER = ("/v1/chat/completions", "/v1/messages", "/v1/responses", "/v1beta/models/{model}:generateContent",
               "/v1/images/generations", "/v1/images/edits", "/v1/video/generations", "/v1/embeddings",
               "/v1/rerank", "/v1/classify")
COPY = {
    "en": {"table": ("Model ID", "Type", "Endpoints"), "note": "Best for",
           "families": ("Family", "Provider", "Models", "Types"), "none": "—"},
    "zh": {"table": ("模型 ID", "类型", "端点"), "note": "适合",
           "families": ("系列", "厂商", "模型数", "类型"), "none": "—"},
}


def kind_of(model: dict) -> str:
    """The model's type; the endpoint decides for media and rerank models the list types as text."""
    paths = [route["path"] for route in model.get("routes", [])]
    if any(path.startswith("/v1/video/") for path in paths):
        return "video"
    if any(path.startswith("/v1/images/") for path in paths):
        return "image"
    if "/v1/rerank" in paths:
        return "rerank"
    kind = model.get("model_type")
    return kind if kind in KINDS else "text"


def route_key(path: str) -> tuple[int, str]:
    return (ROUTE_ORDER.index(path) if path in ROUTE_ORDER else len(ROUTE_ORDER), path)


def natural_key(text: str) -> list:
    """Sort key that orders `gpt-5.10` after `gpt-5.9`."""
    return [int(part) if part.isdigit() else part.casefold() for part in re.split(r"(\d+)", text)]


def snapshot_from(price_list: dict) -> dict:
    """The callable models of a price list response, by vendor and model ID."""
    vendors = []
    for vendor in price_list["data"]["vendors"]:
        models = [model for model in vendor.get("models", []) if model.get("pricing_status") == "priced"]
        models.sort(key=lambda model: natural_key(model["name"]))
        if models:
            vendors.append({"vendor": vendor["vendor"], "models": [{
                "id": model["name"],
                "type": kind_of(model),
                "routes": sorted({route["path"] for route in model.get("routes", []) if route.get("method") == "POST"},
                                 key=route_key),
            } for model in models]})
    return {"source": PRICE_LIST, "vendors": sorted(vendors, key=lambda vendor: vendor["vendor"].casefold())}


def fetch_snapshot(url: str = PRICE_LIST, timeout: float = 30) -> dict:
    request = urllib.request.Request(url, headers={"Accept": "application/json", "User-Agent": "aisa-docs-model-pages"})
    with urllib.request.urlopen(request, timeout=timeout) as response:
        return snapshot_from(json.load(response))


def dump(snapshot: dict) -> str:
    return json.dumps(snapshot, indent=2, ensure_ascii=False) + "\n"


def code(text: str) -> str:
    return f"`{text}`"


def cell(text: str) -> str:
    return text.replace("|", "\\|")


def model_table(models: list[dict], notes: dict, language: str) -> str:
    copy = COPY[language]
    noted = any(notes.get(model["id"], {}).get(language) for model in models)
    columns = list(copy["table"]) + ([copy["note"]] if noted else [])
    lines = ["| " + " | ".join(columns) + " |", "| " + " | ".join("---" for _ in columns) + " |"]
    for model in models:
        routes = ("、" if language == "zh" else ", ").join(code(route) for route in model["routes"]) or copy["none"]
        row = [code(model["id"]), KIND_LABELS[language][model["type"]], routes]
        if noted:
            row.append(cell(notes.get(model["id"], {}).get(language) or copy["none"]))
        lines.append("| " + " | ".join(row) + " |")
    return "\n".join(lines)


def kinds_text(models: list[dict], language: str) -> str:
    present = [kind for kind in KINDS if any(model["type"] == kind for model in models)]
    labels = [KIND_LABELS[language][kind] for kind in present]
    if language == "zh":
        return "、".join(labels)
    return ", ".join(labels[:1] + [label.lower() for label in labels[1:]])


def localized(value, language: str) -> str:
    return value.get(language) or value["en"] if isinstance(value, dict) else value


def families_table(snapshot: dict, config: dict, language: str) -> str:
    """Every vendor of the snapshot: configured families first, in config order, then the rest A to Z."""
    copy = COPY[language]
    prefix = "/zh/" if language == "zh" else "/"
    vendors = {vendor["vendor"]: vendor["models"] for vendor in snapshot["vendors"]}
    order = [family["vendor"] for family in config["families"] if family["vendor"] in vendors]
    order += sorted((name for name in vendors if name not in order), key=str.casefold)
    families = {family["vendor"]: family for family in config["families"]}
    lines = ["| " + " | ".join(copy["families"]) + " |", "| --- | --- | ---: | --- |"]
    for name in order:
        family = families.get(name)
        title = localized(family["name"], language) if family else name
        link = f"[{cell(title)}]({prefix}{family['page']})" if family else cell(title)
        provider = localized(family.get("provider", name), language) if family else name
        lines.append(f"| {link} | {cell(provider)} | {len(vendors[name])} | {kinds_text(vendors[name], language)} |")
    return "\n".join(lines)


def replace_block(text: str, start: str, end: str, body: str) -> str:
    first, last = text.find(start), text.find(end)
    if first < 0 or last < first:
        raise ValueError(f"missing {start} ... {end}")
    return text[:first] + start + "\n" + body + "\n" + text[last:]


def expected_pages(root: Path, snapshot: dict, config: dict) -> tuple[dict[str, str], list[str]]:
    """The generated pages by repository path, and problems that need a person."""
    pages, problems = {}, []
    vendors = {vendor["vendor"]: vendor["models"] for vendor in snapshot["vendors"]}
    notes = config.get("notes", {})
    for family in config["families"]:
        models = vendors.get(family["vendor"])
        if models is None:
            problems.append(f"{family['vendor']}: no callable models on the price list; remove its family page")
            models = []
        for language, name in (("en", f"{family['page']}.mdx"), ("zh", f"zh/{family['page']}.mdx")):
            path = root / name
            if not path.exists():
                problems.append(f"{name}: missing family page")
                continue
            pages[name] = replace_block(path.read_text(), TABLE_START, TABLE_END, model_table(models, notes, language))
    configured = {family["vendor"] for family in config["families"]}
    for name in sorted(set(vendors) - configured, key=str.casefold):
        problems.append(f"{name}: on the price list without a family page; it is listed in the Model Catalog only")
    for language, name in (("en", f"{CATALOG_PAGE}.mdx"), ("zh", f"zh/{CATALOG_PAGE}.mdx")):
        path = root / name
        pages[name] = replace_block(path.read_text(), FAMILIES_START, FAMILIES_END,
                                    families_table(snapshot, config, language))
    return pages, problems


def load(root: Path) -> tuple[dict, dict]:
    return (json.loads((root / SNAPSHOT_PATH).read_text()), json.loads((root / FAMILIES_PATH).read_text()))


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--root", type=Path, default=ROOT)
    parser.add_argument("--refresh", action="store_true", help="update catalog/models.json from the live price list")
    parser.add_argument("--check", action="store_true", help="fail if a generated block is stale; write nothing")
    args = parser.parse_args()
    snapshot, config = load(args.root)
    if args.refresh:
        try:
            live = fetch_snapshot()
        except Exception as error:  # Keep the last good snapshot; the next run retries.
            print(f"warning: could not read {PRICE_LIST} ({error}); keeping the saved snapshot", file=sys.stderr)
        else:
            if live != snapshot and not args.check:
                (args.root / SNAPSHOT_PATH).write_text(dump(live))
            snapshot = live
    pages, problems = expected_pages(args.root, snapshot, config)
    for problem in problems:
        print(f"warning: {problem}", file=sys.stderr)
    stale = [name for name, text in pages.items() if (args.root / name).read_text() != text]
    if args.check:
        if stale or any("missing family page" in problem for problem in problems):
            print("model pages are stale; run scripts/model_pages.py: " + ", ".join(stale), file=sys.stderr)
            return 1
        print(f"model pages match the snapshot; families={len(config['families'])}")
        return 0
    for name in stale:
        (args.root / name).write_text(pages[name])
    models = sum(len(vendor["models"]) for vendor in snapshot["vendors"])
    print(f"model pages written; vendors={len(snapshot['vendors'])} models={models} changed={len(stale)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
